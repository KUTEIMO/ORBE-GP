const STORAGE_KEY = "orbe_lang";

export function getLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "es") return stored;
  const browser = (navigator.language || "es").slice(0, 2);
  return browser === "en" ? "en" : "es";
}

export function setLang(lang) {
  const next = lang === "en" ? "en" : "es";
  localStorage.setItem(STORAGE_KEY, next);
  applyI18n(next);
  document.documentElement.lang = next;
  window.dispatchEvent(new CustomEvent("orbe:lang", { detail: next }));
  return next;
}

export function t(key, lang = getLang()) {
  return STRINGS[lang]?.[key] ?? STRINGS.es[key] ?? key;
}

export function applyI18n(lang = getLang()) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const value = t(key, lang);
    if (el.hasAttribute("data-i18n-attr")) {
      el.setAttribute(el.getAttribute("data-i18n-attr"), value);
    } else {
      el.textContent = value;
    }
  });

  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) titleEl.textContent = t("meta.title", lang);

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", t("meta.description", lang));

  const themeBtn = document.getElementById("themeToggle");
  if (themeBtn) {
    const isDark = document.documentElement.getAttribute("data-theme") === "dark";
    themeBtn.setAttribute(
      "aria-label",
      t(isDark ? "nav.theme.light" : "nav.theme.dark", lang)
    );
  }

  const langBtn = document.getElementById("langToggle");
  if (langBtn) {
    langBtn.setAttribute("aria-label", t("nav.lang", lang));
    langBtn.textContent = lang === "es" ? "EN" : "ES";
  }
}
